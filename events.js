const MONTHS_NOM = ['Январь','Февраль','Март','Апрель','Май','Июнь','Июль','Август','Сентябрь','Октябрь','Ноябрь','Декабрь'];
const WEEKDAYS = ['вс','пн','вт','ср','чт','пт','сб'];

// Ближайший день события, который ещё не прошёл (или null)
function nextDate(ev){ return openDates(ev)[0] || null; }

// Предстоящие события по ближайшей дате
function upcomingEvents(){
  return EVENTS.filter(e => nextDate(e) && !e.hidden).sort((a, b) => parseDay(nextDate(a)) - parseDay(nextDate(b)));
}

// Прошедшие события, свежие первыми
function pastEvents(){
  return EVENTS.filter(e => !nextDate(e) && !e.hidden).sort((a, b) => parseDay(b.dates[b.dates.length - 1]) - parseDay(a.dates[a.dates.length - 1]));
}

function weekday(iso){ return WEEKDAYS[parseDay(iso).getDay()]; }
